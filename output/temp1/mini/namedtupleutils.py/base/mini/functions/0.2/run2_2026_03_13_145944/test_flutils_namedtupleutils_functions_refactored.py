    # Convert the tuple to a namedtuple-like structure
    nt_from_tuple = namedtuple_utils.to_namedtuple(combo)

    # Final conversion of the original OrderedDict (repeat)
    nt_final = namedtuple_utils.to_namedtuple(ordered)

